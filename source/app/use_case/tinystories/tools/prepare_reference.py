"""Generate greedy host PT2 references for the TinyStories board use case."""

import argparse
import importlib
import json
from pathlib import Path

import torch
from pytorch_tokenizers import get_tokenizer


def main():
    """Save prompt and autoregressive predictions from the supplied checkpoint."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('checkpoint', type=Path)
    parser.add_argument('tokenizer', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--header', type=Path, required=True)
    args = parser.parse_args()
    importlib.import_module('executorch.exir.passes._quant_patterns_and_replacements')
    importlib.import_module('torchao.quantization.pt2e.quantize_pt2e')
    torch.set_num_threads(2)
    model = torch.export.load(args.checkpoint).module(check_guards=False)
    tokenizer = get_tokenizer(str(args.tokenizer))
    prompt = [1, 9038, 2501, 263, 931, 297, 263, 2319, 5720, 29892]
    cache_count = 0
    with torch.no_grad():
        for name, buffer in model.named_buffers():
            if 'k_cache' in name or 'v_cache' in name:
                buffer.zero_()
                cache_count += 1
        if cache_count != 16:
            raise ValueError(f'Expected 16 cache buffers, found {cache_count}')
        tokens = list(prompt)
        prompt_top1 = []
        generated = []
        for position in range(len(prompt) + 16 - 1):
            logits = model(torch.tensor([[tokens[position]]], dtype=torch.int64),
                           {'input_pos': torch.tensor([position], dtype=torch.int32)})
            next_token = int(logits.reshape(-1).argmax())
            if position < len(prompt):
                prompt_top1.append(next_token)
            if position >= len(prompt) - 1:
                generated.append(next_token)
                tokens.append(next_token)
    result = {'checkpoint': str(args.checkpoint), 'prompt_tokens': prompt,
              'prompt_top1': prompt_top1, 'generated_tokens': generated,
              'text': tokenizer.decode(tokens),
              'reference_kind': 'Host quantized PT2, greedy argmax; not NPU bit-exact logits'}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2), encoding='utf-8')
    header = ('// SPDX-FileCopyrightText: Copyright 2026 Arm Limited and/or its affiliates\n'
              '// <open-source-office@arm.com>\n// SPDX-License-Identifier: Apache-2.0\n'
              '// Generated by tools/prepare_reference.py from the matching quantized PT2.\n'
              '#pragma once\n#include <cstdint>\nnamespace arm::app::tinystories {\n')
    for name, values in [('kPromptTokens', prompt), ('kPromptExpected', prompt_top1),
                         ('kGeneratedExpected', generated)]:
        header += f'constexpr int32_t {name}[] = {{{", ".join(map(str, values))}}};\n'
    args.header.write_text(header + '} // namespace arm::app::tinystories\n', encoding='utf-8')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
